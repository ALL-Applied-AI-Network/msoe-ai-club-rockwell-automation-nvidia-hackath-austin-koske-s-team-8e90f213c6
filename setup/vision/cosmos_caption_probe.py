"""Narrow Cosmos to visual captions; construct status messages from recorded facts."""
import argparse
import json
from pathlib import Path
import shutil
import time

from liquid_specialists_data import read, write, sha
from cosmos_event_review import MODEL, REVISION, load_clip

PROMPT = '''This is a fixed vial-filling station. In one short sentence, describe
the visible liquid and receiving container at the filling nozzle in this video.
Do not infer recipe, composition, contamination, acceptance, delivered volume or
final dispensing completion. Describe visible action only. If unclear, say so.'''
CROP = [250, 50, 355, 460]


def main(a):
    import cv2
    import numpy as np
    import torch
    import transformers
    if a.out.exists():
        raise ValueError('Use a fresh output directory')
    manifest = read(a.cases/'manifest.json')
    if manifest['run'] != 4 or manifest['run5_used'] or manifest['quality_truth_available']:
        raise ValueError('Unexpected experimental scope')
    for case in manifest['cases']:
        for name, digest in case['artifacts'].items():
            if sha(a.cases/case['id']/name) != digest:
                raise ValueError('Event evidence changed')
    a.out.mkdir(parents=True)
    shutil.copy2(__file__, a.out/Path(__file__).name)
    write(a.out/'plan.json', {'model': MODEL, 'revision': REVISION, 'prompt': PROMPT,
        'frames_per_clip': 8, 'max_new_tokens': 96, 'repetition_penalty': 1.1,
        'station_crop_xyxy': CROP, 'crop_resized_wh': [192, 768],
        'prompt_scope': 'visual caption only; fixed station context supplied',
        'status_origin': 'deterministic recorded evidence, never generated by VLM',
        'cases_sha256': sha(a.cases/'manifest.json'), 'run5_used': False, 'hardware_actions': 0})
    transformers.set_seed(19)
    start = time.perf_counter()
    processor = transformers.AutoProcessor.from_pretrained(MODEL, revision=REVISION)
    model = transformers.Cosmos3EdgeForConditionalGeneration.from_pretrained(MODEL,
        revision=REVISION, dtype=torch.bfloat16, device_map='cuda:0', attn_implementation='sdpa')
    model.eval()
    load_seconds = time.perf_counter()-start
    records = []
    for case in manifest['cases']:
        full, metadata, trace = load_clip(a.cases/case['video'], 8)
        for mode in ('full_frame', 'station_crop'):
            pixels = full
            meta = dict(metadata)
            if mode == 'station_crop':
                x, y, r, b = CROP
                pixels = np.stack([cv2.resize(im[y:b, x:r], (192, 768), interpolation=cv2.INTER_CUBIC) for im in full])
                meta.update(width=192, height=768)
            messages = [{'role': 'user', 'content': [{'type': 'video', 'video': pixels},
                                                    {'type': 'text', 'text': PROMPT}]}]
            torch.cuda.reset_peak_memory_stats()
            torch.cuda.synchronize()
            start = time.perf_counter()
            inputs = processor.apply_chat_template(messages, tokenize=True, add_generation_prompt=True,
                return_dict=True, return_tensors='pt', enable_thinking=False,
                processor_kwargs={'do_sample_frames': False, 'video_metadata': [meta]}).to(model.device)
            with torch.inference_mode():
                generated = model.generate(**inputs, do_sample=False, max_new_tokens=96, repetition_penalty=1.1)
            torch.cuda.synchronize()
            elapsed = time.perf_counter()-start
            trimmed = generated[:, inputs['input_ids'].shape[1]:]
            text = processor.batch_decode(trimmed, skip_special_tokens=True)[0].strip()
            if '</think>' in text:
                text = text.split('</think>', 1)[1].strip()
            context = read(a.cases/case['context'])
            qa_count = sum(s['sample_qa_passes'] for s in context['samples'])
            packet = {'visible_summary': text, 'quality_assessment': 'unavailable',
                'limitations': ['Missing intended recipe, acceptable reference, metering and reviewed geometry.'],
                'operator_message': f'Recipe assessment unavailable. Image sample QA passes {qa_count}/{len(context["samples"])} provisional samples; this does not approve the vial.'}
            record = {'case': case['id'], 'mode': mode, 'caption': text,
                'parsed': packet, 'contract_error': None if text else 'empty_caption',
                'status_origin': 'deterministic_recorded_evidence',
                'caption_semantic_review': 'pending_independent_review',
                'seconds': elapsed, 'input_tokens': inputs['input_ids'].shape[1],
                'output_tokens': trimmed.shape[1], 'generation_hit_token_limit': trimmed.shape[1] >= 96,
                'sampled_input_frames': trace,
                'vlm_pixel_sha256': __import__('hashlib').sha256(pixels.tobytes()).hexdigest(),
                'video_sha256': sha(a.cases/case['video']),
                'peak_allocated_bytes': torch.cuda.max_memory_allocated(),
                'hardware_command': 'none', 'quality_accuracy': None}
            records.append(record)
            write(a.out/f'{case["id"]}-{mode}.json', record)
            print(json.dumps({'case': case['id'], 'mode': mode, 'seconds': elapsed, 'caption': text}), flush=True)
            del inputs, generated, trimmed
    write(a.out/'completed.json', {'model': MODEL, 'revision': REVISION, 'torch': torch.__version__,
        'transformers': transformers.__version__, 'gpu': torch.cuda.get_device_name(0),
        'load_seconds': load_seconds, 'responses': len(records),
        'status_messages_generated_by_vlm': 0, 'semantic_accuracy': None,
        'hardware_actions': 0, 'artifacts': {p.name: sha(p) for p in a.out.iterdir() if p.is_file()}})


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--cases', type=Path, required=True)
    p.add_argument('--out', type=Path, required=True)
    main(p.parse_args())
